/*Tipos primitivos em JavaScript */

//String, Number, Boolean, Null, Undefined, (*Symbol*)

var nome = "Matheus"; // String
var idade = 33; // Number
var altura = 1.80; // Number
var peso = 68; // Number
var estaAbaixoDoPeso = false; // Boolean (true ou false)
var nulo = null; // Null -> variável declarada, mas com valor nulo (intencionalmente sem valor)
var indefinido; // Undefined -> variável declarada, mas sem valor atribuído

console.log("Nome:", nome);
console.log("Idade:", idade);
console.log("Altura:", altura);
console.log("Peso:", peso);
console.log("Está abaixo do peso?", estaAbaixoDoPeso);
console.log("Valor nulo:", nulo);
console.log("Valor indefinido:", indefinido);